export function getAssetSpec(slug: string): AssetSpec | null {
  return ASSET_SPECS[slug] || null;
}

export function formatAssetPrice(value: number, spec?: { unit?: string; decimals?: number; type?: string }): string {
  const dec =
    typeof spec?.decimals === 'number'
      ? spec.decimals
      : spec?.type === 'currency'
        ? 4
        : 2;

  const formatted = new Intl.NumberFormat('tr-TR', {
    minimumFractionDigits: dec,
    maximumFractionDigits: dec,
  }).format(value);

  if (spec?.unit === 'USD') return `$${formatted}`;
  if (spec?.unit === 'RATIO') return formatted;
  return `${formatted} ₺`;
}
